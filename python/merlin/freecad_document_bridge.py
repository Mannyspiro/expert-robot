"""Generate a FreeCAD macro that imports a document and exports assembly meshes.

The macro runs inside an operator-installed FreeCAD process. It supports FCStd
and STEP source documents and writes a bounded, provenance-labelled JSON mesh
payload suitable for the Merlin CAD workspace. It does not execute here.
"""
from __future__ import annotations

import json
from pathlib import Path


def build_document_export_macro(
    source_document: str | Path,
    output_json: str | Path,
    *,
    mesh_deflection_mm: float = 0.5,
    max_objects: int = 500,
    max_vertices_per_object: int = 20000,
    max_faces_per_object: int = 40000,
) -> str:
    source = Path(source_document).expanduser().resolve()
    target = Path(output_json).expanduser().resolve()
    if source.suffix.lower() not in {".fcstd", ".step", ".stp"}:
        raise ValueError("FreeCAD source must be .FCStd, .step or .stp")
    if not isinstance(mesh_deflection_mm, (int, float)) or isinstance(mesh_deflection_mm, bool) or not 0.01 <= mesh_deflection_mm <= 20:
        raise ValueError("mesh_deflection_mm must be between 0.01 and 20")
    for value, label, maximum in (
        (max_objects, "max_objects", 500),
        (max_vertices_per_object, "max_vertices_per_object", 20000),
        (max_faces_per_object, "max_faces_per_object", 40000),
    ):
        if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= maximum:
            raise ValueError(label + " is outside the supported bound")
    return f'''# Generated by Merlin. Review the source path and limits before running.
import FreeCAD as App
import Import
import json
import os

SOURCE = {json.dumps(str(source))}
OUTPUT = {json.dumps(str(target))}
DEFLECTION = {float(mesh_deflection_mm)!r}
MAX_OBJECTS = {max_objects}
MAX_VERTICES = {max_vertices_per_object}
MAX_FACES = {max_faces_per_object}

if SOURCE.lower().endswith(".fcstd"):
    DOC = App.openDocument(SOURCE)
else:
    DOC = App.newDocument("Merlin_STEP_Import")
    Import.insert(SOURCE, DOC.Name)
DOC.recompute()

objects = []
by_name = {{obj.Name: obj for obj in DOC.Objects}}
shape_objects = [obj for obj in DOC.Objects if hasattr(obj, "Shape") and not obj.Shape.isNull()]
if len(shape_objects) > MAX_OBJECTS:
    raise RuntimeError("Document exceeds MAX_OBJECTS; export a smaller assembly or raise the reviewed bound")

for obj in shape_objects:
    shape = obj.Shape.copy()
    try:
        placement = obj.getGlobalPlacement()
        shape.Placement = placement.multiply(shape.Placement)
    except Exception:
        pass
    vertices, facets = shape.tessellate(DEFLECTION)
    if len(vertices) > MAX_VERTICES or len(facets) > MAX_FACES:
        raise RuntimeError("Object mesh exceeds configured vertex/face bounds: " + obj.Name)
    mesh_vertices = [[float(v.x), float(v.y), float(v.z)] for v in vertices]
    mesh_faces = [[int(i) for i in face] for face in facets]
    box = shape.BoundBox
    group = getattr(obj, "Group", []) or []
    children = [child.Name for child in group if hasattr(child, "Name")]
    objects.append({{
        "ref": obj.Name,
        "name": obj.Label,
        "type_id": obj.TypeId,
        "assembly_children": children,
        "bounds_mm": {{
            "min": [float(box.XMin), float(box.YMin), float(box.ZMin)],
            "max": [float(box.XMax), float(box.YMax), float(box.ZMax)]
        }},
        "position_mm": [float(box.Center.x), float(box.Center.y), float(box.Center.z)],
        "size_mm": [float(box.XLength), float(box.YLength), float(box.ZLength)],
        "mesh": {{"vertices": mesh_vertices, "faces": mesh_faces}}
    }})

payload = {{
    "schema": "merlin-freecad-document-mesh/1",
    "source_document": SOURCE,
    "document_name": DOC.Label,
    "units": "mm",
    "object_count": len(objects),
    "objects": objects,
    "assemblies": [
        {{"ref": obj.Name, "name": obj.Label,
          "children": [child.Name for child in (getattr(obj, "Group", []) or []) if hasattr(child, "Name")]}}
        for obj in DOC.Objects if getattr(obj, "Group", None)
    ]
}}
os.makedirs(os.path.dirname(OUTPUT) or ".", exist_ok=True)
with open(OUTPUT, "w", encoding="utf-8") as stream:
    json.dump(payload, stream, sort_keys=True, separators=(",", ":"))
print("Merlin FreeCAD document export complete: " + OUTPUT)
'''
 
 
__all__ = ["build_document_export_macro"]
