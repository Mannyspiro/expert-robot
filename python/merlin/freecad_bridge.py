"""Generate a FreeCAD macro and wiring netlist from canonical Engineering IR.

This creates an executable import macro; it does not install or launch FreeCAD.
Geometry is emitted from the validated v1 box model, with pins as optional markers.
"""
from __future__ import annotations

import base64
import json
from pathlib import Path
from typing import Any

from merlin.engineering_ir import EngineeringProject, export_netlist, validate_project


def build_freecad_macro(project: EngineeringProject, output_fcstd: str | Path,
                        output_step: str | Path | None = None) -> str:
    issues = validate_project(project)
    errors = [issue for issue in issues if issue.severity == "error"]
    if errors:
        raise ValueError("cannot export invalid Engineering IR: " +
                         "; ".join(issue.code for issue in errors))
    payload = {
        "name": project.name,
        "parts": [
            {"ref": part.ref, "name": part.name, "size_mm": list(part.size_mm),
             "position_mm": list(part.position_mm),
             "pins": [
                 {"number": pin.number, "name": pin.name,
                  "position_mm": list(pin.position_mm) if pin.position_mm else None}
                 for pin in part.pins
             ]}
            for part in project.parts
        ],
    }
    encoded = base64.b64encode(json.dumps(payload, sort_keys=True).encode("utf-8")).decode("ascii")
    fcstd = str(Path(output_fcstd).expanduser().resolve())
    step = str(Path(output_step).expanduser().resolve()) if output_step else ""
    return f'''# Generated by Merlin Engineering IR. Review before fabrication.
import App, Part, Import, json, base64
from FreeCAD import Vector

DATA = json.loads(base64.b64decode("{encoded}").decode("utf-8"))
DOC = App.newDocument("Merlin_" + "".join(c if c.isalnum() else "_" for c in DATA["name"]))
OBJECTS = []
for item in DATA["parts"]:
    sx, sy, sz = item["size_mm"]
    x, y, z = item["position_mm"]
    obj = DOC.addObject("Part::Box", "Part_" + item["ref"].replace("-", "_"))
    obj.Label = item["ref"] + " — " + item["name"]
    obj.Length, obj.Width, obj.Height = sx, sy, sz
    obj.Placement.Base = Vector(x - sx/2.0, y - sy/2.0, z - sz/2.0)
    obj.addProperty("App::PropertyString", "MerlinReference", "Merlin")
    obj.MerlinReference = item["ref"]
    OBJECTS.append(obj)
    for pin in item["pins"]:
        if pin["position_mm"] is None:
            continue
        px, py, pz = pin["position_mm"]
        marker = DOC.addObject("Part::Sphere", "Pin_" + item["ref"] + "_" + pin["number"])
        marker.Label = item["ref"] + "." + pin["number"] + " — " + pin["name"]
        marker.Radius = 0.75
        marker.Placement.Base = Vector(x + px, y + py, z + pz)
        OBJECTS.append(marker)
DOC.recompute()
DOC.saveAs({json.dumps(fcstd)})
if {bool(step)!r}:
    Import.export(OBJECTS, {json.dumps(step)})
print("Merlin FreeCAD import complete. Electrical netlist is a separate validated sidecar.")
'''.replace("import App, Part, Import, json, base64", "import FreeCAD as App, Part, Import, json, base64")


def write_freecad_bundle(project: EngineeringProject, directory: str | Path) -> dict[str, str]:
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    macro_path = target / "merlin_import.FCMacro"
    netlist_path = target / "merlin_netlist.json"
    fcstd_path = target / "merlin_project.FCStd"
    step_path = target / "merlin_project.step"
    macro_path.write_text(build_freecad_macro(project, fcstd_path, step_path), encoding="utf-8")
    netlist_path.write_text(json.dumps(export_netlist(project), indent=2, sort_keys=True),
                            encoding="utf-8")
    return {"macro": str(macro_path), "netlist": str(netlist_path),
            "fcstd_output": str(fcstd_path), "step_output": str(step_path)}


__all__ = ["build_freecad_macro", "write_freecad_bundle"]
