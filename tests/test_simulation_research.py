from copy import deepcopy
from dataclasses import replace
from fractions import Fraction
import json
from pathlib import Path
import sqlite3
import tempfile
import unittest

from merlin.engineering_ir import EngineeringProject, Part, Pin, Net, export_spice_netlist
from merlin.project_registry import MerlinRegistry
from dot_ai_os.simulation_research import (
    CircuitCandidate, CircuitObjective, compare_virtual_circuits, divider_project, virtual_circuit_demo,
)
from dot_ai_os.bridge import canonical


def candidate(name="baseline", upper="1000", lower="1000"):
    return CircuitCandidate(name, {"V1": {"kind": "V", "value": "5"},
        "R1": {"kind": "R", "value": upper}, "R2": {"kind": "R", "value": lower}})


class VirtualCircuitTests(unittest.TestCase):
    def setUp(self):
        self.project = divider_project()
        self.objective = CircuitObjective("GND", "OUT", "2.5", "0.01", "0.1")

    def run_comparison(self, **values):
        defaults = dict(project=self.project, baseline=candidate(),
                        candidates=(candidate("lower_power", "9000", "9000"),),
                        objective=self.objective, source_commit="a" * 40)
        defaults.update(values)
        return compare_virtual_circuits(**defaults)

    def test_known_divider_voltage_currents_power_and_source_export(self):
        report = self.run_comparison()
        baseline = report["results"][0]
        self.assertEqual(Fraction(baseline["node_voltage_v"]["OUT"]), Fraction(5, 2))
        self.assertEqual(Fraction(baseline["branch_current_a_declared_pin_order"]["R1"]), Fraction(1, 400))
        self.assertEqual(Fraction(baseline["total_resistor_power_w"]), Fraction(1, 80))
        self.assertEqual(baseline["maximum_kcl_residual_a"], "0")
        self.assertEqual(baseline["power_balance_residual_w"], "0")
        self.assertEqual(baseline["spice_netlist"], export_spice_netlist(self.project,
            candidate().component_specs, ground_net="GND", measure_nets=("OUT",)))
        self.assertEqual(report["wiring_netlist"]["format"], "merlin-netlist-v1")
        self.assertIn("Generated by Merlin Engineering IR", report["cad_preview_openscad"])

    def test_lower_power_at_matched_output_is_followup_only(self):
        report = self.run_comparison()
        self.assertEqual(report["selected_for_followup"], "lower_power")
        self.assertEqual(report["decision"], "review_required")
        self.assertFalse(report["qualification"])
        self.assertFalse(report["promotion_authority"])
        self.assertFalse(report["physical_safety_certification"])
        self.assertFalse(report["formal_proof"])
        self.assertEqual(report["independent_cace_status"], "not_run")
        self.assertEqual(report["epistemic_status"], "simulated")

    def test_loaded_divider_uses_connectivity_not_unloaded_formula(self):
        pins = (Pin("1", "one"), Pin("2", "two"))
        project = replace(self.project,
            parts=self.project.parts + (Part("R3", "Virtual load", pins),),
            nets=(self.project.nets[0], Net("OUT", ("R1.2", "R2.1", "R3.1")),
                  Net("GND", ("V1.2", "R2.2", "R3.2"))))
        baseline = candidate()
        baseline.component_specs["R3"] = {"kind": "R", "value": "1000"}
        other = deepcopy(baseline.component_specs)
        other["R1"]["value"] = "2000"
        report = self.run_comparison(project=project, baseline=baseline,
            candidates=(CircuitCandidate("other", other),))
        expected_bottom = Fraction(1, Fraction(1, 1000) + Fraction(1, 1000))
        expected = 5 * expected_bottom / (1000 + expected_bottom)
        self.assertEqual(Fraction(report["results"][0]["node_voltage_v"]["OUT"]), expected)
        self.assertNotEqual(expected, Fraction(5, 2))

    def test_floating_island_is_rejected(self):
        pins = (Pin("1", "one"), Pin("2", "two"))
        project = replace(self.project,
            parts=self.project.parts + (Part("R3", "Floating", pins), Part("R4", "Floating", pins)),
            nets=self.project.nets + (Net("ISLAND_A", ("R3.1", "R4.1")),
                                      Net("ISLAND_B", ("R3.2", "R4.2"))))
        baseline = candidate()
        for ref in ("R3", "R4"):
            baseline.component_specs[ref] = {"kind": "R", "value": "1000"}
        other = CircuitCandidate("other", deepcopy(baseline.component_specs))
        with self.assertRaisesRegex(ValueError, "floating"):
            self.run_comparison(project=project, baseline=baseline, candidates=(other,))

    def test_source_or_kind_changes_cannot_game_comparison(self):
        for change in ({"kind": "V", "value": "0"}, {"kind": "C", "value": "5"}):
            specs = candidate().component_specs
            specs["V1"] = change
            with self.subTest(change=change), self.assertRaises(ValueError):
                self.run_comparison(candidates=(CircuitCandidate("changed", specs),))

    def test_input_bounds_and_nonfinite_or_directive_values_are_rejected(self):
        for bad in ("0", "-1000", "NaN", "inf", "1e999999", "1000\n.control", "1" * 10000):
            with self.subTest(bad=bad[:20]), self.assertRaises(ValueError):
                self.run_comparison(baseline=candidate(upper=bad))
        for maximum in ("0", "1.1", "1e99"):
            with self.subTest(maximum=maximum), self.assertRaises(ValueError):
                self.run_comparison(objective=replace(self.objective, maximum_total_power_w=maximum))
        with self.assertRaises(ValueError):
            self.run_comparison(candidates=tuple(candidate("c" + str(i)) for i in range(5)))

    def test_canonical_ir_errors_missing_parts_and_pin_connections_rejected(self):
        with self.assertRaisesRegex(ValueError, "canonical"):
            self.run_comparison(project=replace(self.project, units="inches"))
        missing = candidate()
        del missing.component_specs["R2"]
        with self.assertRaises(ValueError):
            self.run_comparison(baseline=missing)
        project = replace(self.project, nets=self.project.nets[:-1] + (Net("GND", ("V1.2",)),))
        with self.assertRaises(ValueError):
            self.run_comparison(project=project)

    def test_ratings_prevent_followup_selection_without_claiming_safety(self):
        tight = replace(self.project.parts[1], pins=(Pin("1", "one", max_current_a=0.00001),
                                                   Pin("2", "two", max_current_a=0.00001)))
        report = self.run_comparison(project=replace(self.project,
                                        parts=(self.project.parts[0], tight, self.project.parts[2])))
        self.assertTrue(report["results"][0]["modeled_rating_flags"])
        self.assertIsNone(report["selected_for_followup"])
        self.assertEqual(report["decision"], "no_candidate_meets_model_constraints")

    def test_geometry_change_does_not_infer_electrical_parameters(self):
        shifted = replace(self.project, parts=tuple(replace(part, position_mm=(10.0, 20.0, 30.0),
                                                           size_mm=(50.0, 20.0, 10.0)) for part in self.project.parts))
        first, second = self.run_comparison(), self.run_comparison(project=shifted)
        self.assertEqual(first["results"], second["results"])
        self.assertNotEqual(first["cad_preview_openscad"], second["cad_preview_openscad"])

    def test_repeatability_and_registry_artifact_replay_without_claim_mutation(self):
        with tempfile.TemporaryDirectory() as root:
            registry = MerlinRegistry(root)
            registry.register_project("virtual-lab", "Virtual lab")
            first = self.run_comparison(registry=registry, project_id="virtual-lab")
            second = self.run_comparison(registry=registry, project_id="virtual-lab")
            self.assertEqual(first, second)
            self.assertEqual(first["artifact_ref"]["version"], 1)
            recorded = json.loads(registry.read_artifact_ref(first["artifact_ref"])["content"])
            self.assertEqual(recorded["request_id"], first["request_id"])
            self.assertNotIn("artifact_ref", recorded)
            with sqlite3.connect(registry.db_path) as db:
                self.assertEqual(db.execute("SELECT COUNT(*) FROM claims").fetchone()[0], 0)
                self.assertEqual(db.execute("SELECT COUNT(*) FROM capability_qualification_receipts").fetchone()[0], 0)

    def test_fixed_demo_has_no_caller_selected_execution_paths_or_private_inputs(self):
        report = virtual_circuit_demo({})
        self.assertEqual(report, virtual_circuit_demo({"operation": "demo"}))
        self.assertLessEqual(len(canonical(report)), 48000)
        self.assertEqual(report["selected_for_followup"], "lower_power")
        for arguments in ({"operation": "shell"}, {"path": "/etc/shadow"},
                          {"operation": "demo", "code": "anything"}, {"source_commit": "a" * 40}, []):
            with self.subTest(arguments=arguments), self.assertRaises(ValueError):
                virtual_circuit_demo(arguments)


if __name__ == "__main__":
    unittest.main()
