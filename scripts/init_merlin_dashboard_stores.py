#!/usr/bin/env python3
"""Initialize Merlin's canonical local stores for the read-only HUD dashboard."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shlex

from merlin.event_outbox import MerlinEventOutbox
from merlin.hypothesis_ledger import HypothesisLedger
from merlin.knowledge_graph import MerlinKnowledgeGraph
from merlin.project_registry import MerlinRegistry


def initialize(data_dir: str | Path, *, project_id: str = "merlin-main",
               project_name: str = "Merlin") -> dict[str, object]:
    root = Path(data_dir).expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)

    registry_root = root / "registry"
    graph_db = root / "knowledge-graph.sqlite3"
    outbox_db = root / "event-outbox.sqlite3"
    hypotheses_db = root / "hypotheses.sqlite3"
    events_db = root / "events.sqlite3"
    env_file = root / "merlin-hud.env"

    registry = MerlinRegistry(registry_root)
    try:
        inventory = registry.inventory(project_id)
    except KeyError:
        registry.register_project(
            project_id,
            project_name,
            metadata={
                "purpose": "canonical research dashboard",
                "authority": "qualification-only",
                "promotion_authority": False,
            },
        )
        inventory = registry.inventory(project_id)
    graph = MerlinKnowledgeGraph(graph_db)
    outbox = MerlinEventOutbox(outbox_db)
    hypotheses = HypothesisLedger(hypotheses_db)

    environment = {
        "MERLIN_REGISTRY_ROOT": str(registry_root),
        "MERLIN_GRAPH_DB_PATH": str(graph_db),
        "MERLIN_OUTBOX_DB_PATH": str(outbox_db),
        "MERLIN_HYPOTHESES_DB_PATH": str(hypotheses_db),
        "MERLIN_DB_PATH": str(events_db),
        "MERLIN_PROJECT_ID": project_id,
        "MERLIN_PORT": "8765",
    }
    env_file.write_text(
        "# Generated by scripts/init_merlin_dashboard_stores.py\n"
        + "".join(f"export {key}={shlex.quote(value)}\n"
                  for key, value in environment.items()),
        encoding="utf-8",
    )
    try:
        env_file.chmod(0o600)
    except OSError:
        pass

    snapshot = graph.export_snapshot()
    return {
        "schema": "merlin-dashboard-bootstrap/1",
        "data_dir": str(root),
        "project_id": project_id,
        "project": {
            "project_id": project_id,
            "name": inventory["name"],
            "version": inventory["version"],
            "artifact_count": len(inventory["artifacts"]),
        },
        "graph_summary": {
            "node_count": len(snapshot["nodes"]),
            "edge_count": len(snapshot["edges"]),
            "snapshot_sha256": snapshot["snapshot_sha256"],
        },
        "outbox_counts": outbox.counts(),
        "hypothesis_count": len(hypotheses.list_hypotheses()),
        "environment_file": str(env_file),
        "read_only_dashboard": "http://127.0.0.1:8765/hud",
        "authority": "qualification-only",
        "promotion_authority": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Create or open Merlin canonical stores for the loopback-only HUD."
    )
    parser.add_argument(
        "--data-dir",
        default=str(Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share"))
                    / "merlin"),
    )
    parser.add_argument("--project-id", default="merlin-main")
    parser.add_argument("--project-name", default="Merlin")
    args = parser.parse_args()
    result = initialize(
        args.data_dir, project_id=args.project_id, project_name=args.project_name
    )
    print(json.dumps(result, sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
